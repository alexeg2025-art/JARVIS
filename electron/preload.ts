import { contextBridge, ipcRenderer } from 'electron';
type PendingEmail = { id: string; to: string; subject: string; body: string; createdAt: number };
contextBridge.exposeInMainWorld('jarvis', {
  controlWindow: (action: 'minimize' | 'maximize' | 'close') => ipcRenderer.invoke('window:control', action),
  getSystemInfo: () => ipcRenderer.invoke('system:info'),
  loadSchoolProfile: () => ipcRenderer.invoke('school:profile-load'),
  saveSchoolProfile: (profile: string) => ipcRenderer.invoke('school:profile-save', profile),
  loadHistory: () => ipcRenderer.invoke('history:load'),
  saveHistory: (store: unknown) => ipcRenderer.invoke('history:save', store),
  checkConnection: () => ipcRenderer.invoke('connection:check'),
  hasApiKey: () => ipcRenderer.invoke('settings:key-status'),
  hasFishAudioKey: () => ipcRenderer.invoke('settings:fish-status'),
  getCredentialStatus: () => ipcRenderer.invoke('settings:credential-status'),
  saveCredential: (name: 'groq'|'fish-audio'|'openai', key: string) => ipcRenderer.invoke('settings:credential-save', name, key),
  speakText: (text: string) => ipcRenderer.invoke('voice:speak', text),
  transcribeAudio: (audioBase64: string, mimeType: string) => ipcRenderer.invoke('voice:transcribe', audioBase64, mimeType),
  openGmailDraft: (draft: { to: string; subject: string; body: string }) => ipcRenderer.invoke('email:open-draft', draft),
  gmailStatus: () => ipcRenderer.invoke('gmail:status'),
  smsConfig: () => ipcRenderer.invoke('sms:config-get'),
  saveSmsConfig: (config: { accountSid: string; authToken: string; from: string; to: string }) => ipcRenderer.invoke('sms:config-save', config),
  connectGmail: (clientId: string, clientSecret: string) => ipcRenderer.invoke('gmail:connect', clientId, clientSecret),
  disconnectGmail: () => ipcRenderer.invoke('gmail:disconnect'),
  confirmEmail: (id: string) => ipcRenderer.invoke('email:confirm', id),
  cancelEmail: (id: string) => ipcRenderer.invoke('email:cancel', id),
  openPrintableInSlicer: () => ipcRenderer.invoke('printer:open-file'),
  createModelSource: (prompt: string) => ipcRenderer.invoke('model:create-source', prompt),
  createBlenderModel: (description: string) => ipcRenderer.invoke('model:create-blender', description) as Promise<{ title: string; blendPath: string; scriptPath: string }>,
  openBlendFile: () => ipcRenderer.invoke('model:open-blend') as Promise<{ opened: boolean; filePath?: string }>,
  showModelFile: (path: string) => ipcRenderer.invoke('model:show-file', path),
  sendMessage: (messages: { role: 'user' | 'assistant'; content: string }[], model?: string) => ipcRenderer.invoke('chat:send', { messages, model }),
  onToken: (callback: (token: string) => void) => { const listener = (_: Electron.IpcRendererEvent, token: string) => callback(token); ipcRenderer.on('chat:token', listener); return () => ipcRenderer.removeListener('chat:token', listener); },
  onDone: (callback: () => void) => { const listener = () => callback(); ipcRenderer.on('chat:done', listener); return () => ipcRenderer.removeListener('chat:done', listener); },
  onPendingEmail: (callback: (email: PendingEmail | null) => void) => { const listener = (_: Electron.IpcRendererEvent, email: PendingEmail | null) => callback(email); ipcRenderer.on('email:pending', listener); return () => ipcRenderer.removeListener('email:pending', listener); },
});
